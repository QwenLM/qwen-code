import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const scriptPath = relative(root, fileURLToPath(import.meta.url));
const generatedCliDir = join(root, 'packages/cli/src/generated');
const cliGitCommitFile = join(generatedCliDir, 'git-commit.ts');
const generatedCoreDir = join(root, 'packages/core/src/generated');
const coreGitCommitFile = join(generatedCoreDir, 'git-commit.ts');
let gitCommitInfo = 'N/A';
let cliVersion = 'UNKNOWN';

function isUsableEnvVersion(value) {
  return (
    typeof value === 'string' && value.length > 0 && !value.includes('${{')
  );
}

function normalizeEnvVersion(value) {
  return value.replace(/^v(?=\d)/, '');
}

function versionFromEnv() {
  const candidates = [
    process.env.RELEASE_VERSION_STRIPPED,
    process.env.CLI_VERSION,
    process.env.PRODUCT_VERSION,
    process.env.RELEASE_VERSION,
    process.env.VERSION,
  ];

  for (const candidate of candidates) {
    if (isUsableEnvVersion(candidate)) {
      return normalizeEnvVersion(candidate);
    }
  }

  return undefined;
}

if (!existsSync(generatedCliDir)) {
  mkdirSync(generatedCliDir, { recursive: true });
}

if (!existsSync(generatedCoreDir)) {
  mkdirSync(generatedCoreDir, { recursive: true });
}

try {
  const gitHash = execSync('git rev-parse --short HEAD', {
    encoding: 'utf-8',
  }).trim();
  if (gitHash) {
    gitCommitInfo = gitHash;
  }
} catch {
  // ignore
}

try {
  const envVersion = versionFromEnv();
  if (envVersion) {
    cliVersion = envVersion;
  } else {
    const packageJson = JSON.parse(
      readFileSync(join(root, 'package.json'), 'utf8'),
    );
    cliVersion =
      typeof packageJson.version === 'string' ? packageJson.version : 'UNKNOWN';
  }
} catch {
  // ignore
}

const fileContent = `/**
 * @license
 * Copyright ${new Date().getUTCFullYear()} Google LLC
 * SPDX-License-Identifier: Apache-2.0
 */

// This file is auto-generated by the build script (${scriptPath})
// Do not edit this file manually.
export const GIT_COMMIT_INFO = '${gitCommitInfo}';
export const CLI_VERSION = '${cliVersion}';
`;

writeFileSync(cliGitCommitFile, fileContent);
writeFileSync(coreGitCommitFile, fileContent);

// Seed the embedded-assets-bun.ts stub so that packages/core/src/utils/
// runtimeAssetPath.ts can `import { EMBEDDED_ASSETS }` in fresh checkouts
// (the real imports are injected later by scripts/generate-embedded-assets.ts
// during the Bun bundle step). We write a stub here — not the populated form —
// because Node/Vitest are what run after `npm run generate`, and `with { type:
// 'file' }` import attributes are Bun-only.
const embeddedAssetsStub = `/**
 * @license
 * Copyright ${new Date().getUTCFullYear()} Google LLC
 * SPDX-License-Identifier: Apache-2.0
 */

// This file is rewritten in-place by scripts/generate-embedded-assets.ts
// during the Bun bundle step, which adds \`import ... with { type: 'file' }\`
// statements so that \`bun build --compile\` embeds each asset into the final
// binary. After the build completes, bun-binary-compiler.ts restores this stub
// so the file stays Node/Vitest-safe in dev and tests.
//
// Keys are repo-relative paths (the third argument to resolveRuntimeAssetPath);
// values are absolute paths that Bun resolves to /$bunfs/... at runtime.

export const EMBEDDED_ASSETS: Readonly<Record<string, string>> = {};
`;
writeFileSync(
  join(generatedCoreDir, 'embedded-assets-bun.ts'),
  embeddedAssetsStub,
);

// Same pattern for the native-modules manifest. Keys/values match the shape
// in scripts/generate-embedded-natives.ts; when populated, the file contains
// `import ... with { type: 'file' }` statements that Bun compile bakes into
// the binary. The bootstrap extractor in packages/core/src/bootstrap/
// bunNativesBootstrap.ts reads this map.
const embeddedNativesStub = `/**
 * @license
 * Copyright ${new Date().getUTCFullYear()} Google LLC
 * SPDX-License-Identifier: Apache-2.0
 */

// This file is rewritten in-place by scripts/generate-embedded-natives.ts
// during the Bun bundle step. This stub keeps dev/Vitest (Node) happy.

export interface EmbeddedNativeFile {
  path: string;
  mode: number;
}
export const EMBEDDED_NATIVES: Readonly<Record<string, EmbeddedNativeFile>> = {};
`;
writeFileSync(
  join(generatedCoreDir, 'embedded-natives-bun.ts'),
  embeddedNativesStub,
);
