/**
 * Return a calendar date in the machine's local timezone.
 *
 * Building the value from date parts avoids depending on locale-specific
 * formatting support while preserving the YYYY-MM-DD representation used in
 * model context.
 */
export function getCurrentLocalDate(): string {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}
