const SESSION_ID_UUID_REGEX =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isValidSessionIdUuid(sessionId: string): boolean {
  return SESSION_ID_UUID_REGEX.test(sessionId);
}
