import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs/promises';
import * as os from 'node:os';
import * as path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import {
  GitWorktreeService,
  WORKTREES_DIR,
  writeWorktreeSessionMarker,
} from './gitWorktreeService.js';
import { cleanupStaleAgentWorktrees } from './worktreeCleanup.js';
import {
  readWorktreeSession,
  restoreWorktreeContext,
  writeWorktreeSession,
} from './worktreeSessionService.js';

const gitEnv = {
  ...process.env,
  GIT_AUTHOR_NAME: 'Test',
  GIT_AUTHOR_EMAIL: 'test@example.com',
  GIT_COMMITTER_NAME: 'Test',
  GIT_COMMITTER_EMAIL: 'test@example.com',
  GIT_CONFIG_GLOBAL: '/dev/null',
  GIT_CONFIG_NOSYSTEM: '1',
};

function git(cwd: string, args: string[]): string {
  return execFileSync('git', args, {
    cwd,
    env: gitEnv,
    encoding: 'utf8',
  }).trim();
}

describe('GitWorktreeService custom worktree.root integration', () => {
  const dirs: string[] = [];

  afterEach(async () => {
    for (const dir of dirs.splice(0)) {
      await fs.rm(dir, { recursive: true, force: true });
    }
  });

  async function initRepo(): Promise<{ root: string; repo: string }> {
    const root = await fs.mkdtemp(path.join(os.tmpdir(), 'wt-custom-root-'));
    dirs.push(root);
    const repo = path.join(root, 'repo');
    await fs.mkdir(repo, { recursive: true });
    git(repo, ['init', '-b', 'main']);
    await fs.writeFile(path.join(repo, 'README.md'), 'hello\n');
    git(repo, ['add', 'README.md']);
    git(repo, ['commit', '-m', 'init']);
    return { root, repo };
  }

  it('creates, ignores, and removes a worktree under a custom worktree.root without touching legacy .qwen/.gitignore', async () => {
    const { repo } = await initRepo();
    await fs.mkdir(path.join(repo, '.qwen'), { recursive: true });
    const legacyGitignore = path.join(repo, '.qwen', '.gitignore');
    const legacyBody = `# Auto-generated by qwen-code.\n${WORKTREES_DIR}/\n`;
    await fs.writeFile(legacyGitignore, legacyBody);

    const service = new GitWorktreeService(repo, {
      worktreeRoot: '.worktrees',
    });
    const created = await service.createUserWorktree('feat-custom', 'main');
    expect(created.success).toBe(true);
    expect(created.worktree?.path).toBe(
      path.join(repo, '.worktrees', 'feat-custom'),
    );

    const excludeContent = await fs.readFile(
      path.join(repo, '.git', 'info', 'exclude'),
      'utf8',
    );
    expect(excludeContent).toContain('/.worktrees/');
    // Legacy .qwen/.gitignore must stay intact when custom root is in use,
    // while .worktrees/ itself must be ignored by .git/info/exclude.
    expect(await fs.readFile(legacyGitignore, 'utf8')).toBe(legacyBody);
    expect(git(repo, ['status', '--porcelain'])).not.toContain('.worktrees');

    const removed = await service.removeUserWorktree('feat-custom', {
      deleteBranch: true,
    });
    expect(removed.success).toBe(true);
    await expect(
      fs.access(path.join(repo, '.worktrees', 'feat-custom')),
    ).rejects.toThrow();
  });

  it('blocks symlinkDirectories entries that overlap the configured custom worktree.root', async () => {
    const { repo } = await initRepo();
    await fs.mkdir(path.join(repo, 'node_modules', 'pkg'), { recursive: true });
    await fs.mkdir(path.join(repo, 'tmp', 'cache'), { recursive: true });
    await fs.writeFile(path.join(repo, 'tmp', 'cache', 'x.txt'), 'ok');

    const service = new GitWorktreeService(repo, { worktreeRoot: 'tmp/wts' });
    const created = await service.createUserWorktree('sym-check', 'main', {
      symlinkDirectories: ['tmp', 'tmp/wts', 'tmp/cache', 'node_modules'],
    });
    expect(created.success).toBe(true);
    const wtPath = created.worktree!.path;

    // Ancestor `tmp` and exact `tmp/wts` must be refused to prevent recursion.
    const tmpStat = await fs.lstat(path.join(wtPath, 'tmp')).catch(() => null);
    expect(tmpStat?.isSymbolicLink() ?? false).toBe(false);
    await expect(fs.lstat(path.join(wtPath, 'tmp', 'wts'))).rejects.toThrow();

    // Unrelated sibling `tmp/cache` and `node_modules` are still symlinked.
    expect(
      (await fs.lstat(path.join(wtPath, 'tmp', 'cache'))).isSymbolicLink(),
    ).toBe(true);
    expect(
      (await fs.lstat(path.join(wtPath, 'node_modules'))).isSymbolicLink(),
    ).toBe(true);
  });

  it('rejects creating a worktree when custom worktree.root is a symlink escaping the repository', async () => {
    const { root, repo } = await initRepo();
    const outside = path.join(root, 'outside');
    await fs.mkdir(outside, { recursive: true });
    await fs.symlink(outside, path.join(repo, '.worktrees'));

    const service = new GitWorktreeService(repo, {
      worktreeRoot: '.worktrees',
    });
    const created = await service.createUserWorktree('escape-test', 'main');
    expect(created.success).toBe(false);
    expect(created.code).toBe('invalid_worktree_root');
    expect(await fs.readdir(outside)).toEqual([]);
  });

  it('sweeps stale agent worktrees under custom worktree.root and skips invalid roots', async () => {
    const { repo } = await initRepo();
    const service = new GitWorktreeService(repo, {
      worktreeRoot: '.worktrees',
    });
    const created = await service.createUserWorktree('agent-1234abc', 'main');
    expect(created.success).toBe(true);

    // Invalid root fails closed without touching the checkout.
    expect(
      await cleanupStaleAgentWorktrees(repo, {
        cutoffMs: -1,
        worktreeRoot: '../escape',
      }),
    ).toBe(0);
    await expect(fs.access(created.worktree!.path)).resolves.toBeUndefined();

    // Valid custom root cleans up the stale agent checkout.
    expect(
      await cleanupStaleAgentWorktrees(repo, {
        cutoffMs: -1,
        worktreeRoot: '.worktrees',
      }),
    ).toBe(1);
    await expect(fs.access(created.worktree!.path)).rejects.toThrow();
  });

  it('restores a worktree session sidecar under custom worktree.root and fails closed on invalid root without clearing sidecar', async () => {
    const { root, repo } = await initRepo();
    const service = new GitWorktreeService(repo, {
      worktreeRoot: '.worktrees',
    });
    const created = await service.createUserWorktree('resume-custom', 'main');
    expect(created.success).toBe(true);
    const sessionId = '11111111-1111-4111-8111-111111111111';
    await writeWorktreeSessionMarker(created.worktree!.path, sessionId);

    const sidecarPath = path.join(root, `${sessionId}.worktree.json`);
    await writeWorktreeSession(sidecarPath, {
      slug: 'resume-custom',
      worktreePath: created.worktree!.path,
      worktreeBranch: created.worktree!.branch,
      originalCwd: repo,
      originalBranch: 'main',
      originalHeadCommit: git(repo, ['rev-parse', 'HEAD']),
    });

    // Invalid worktree.root setting must NOT clear the sidecar.
    const invalidWarnings: unknown[] = [];
    const invalidRestore = await restoreWorktreeContext(
      sidecarPath,
      (err) => invalidWarnings.push(err),
      sessionId,
      '../escape',
    );
    expect(invalidRestore.session).toBeNull();
    expect(invalidWarnings.length).toBeGreaterThan(0);
    expect(await readWorktreeSession(sidecarPath)).not.toBeNull();

    // Valid custom worktree.root restores the session cleanly.
    const restored = await restoreWorktreeContext(
      sidecarPath,
      undefined,
      sessionId,
      '.worktrees',
    );
    expect(restored.session?.slug).toBe('resume-custom');
    expect(restored.contextMessage).toContain(created.worktree!.path);
  });
});
