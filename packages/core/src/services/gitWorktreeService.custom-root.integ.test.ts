import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs/promises';
import * as os from 'node:os';
import * as path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import {
  GitWorktreeService,
  WORKTREES_DIR,
  writeWorktreeSessionMarker,
} from './gitWorktreeService.js';
import { cleanupStaleAgentWorktrees } from './worktreeCleanup.js';
import {
  WorktreeRestoreRefusedError,
  readWorktreeSession,
  restoreWorktreeContext,
  writeWorktreeSession,
} from './worktreeSessionService.js';
import { SessionService } from './sessionService.js';
import { SessionReferenceService } from './session-reference-service.js';
import { Storage } from '../config/storage.js';

const gitEnv = {
  ...process.env,
  GIT_AUTHOR_NAME: 'Test',
  GIT_AUTHOR_EMAIL: 'test@example.com',
  GIT_COMMITTER_NAME: 'Test',
  GIT_COMMITTER_EMAIL: 'test@example.com',
  GIT_CONFIG_GLOBAL: '/dev/null',
  GIT_CONFIG_NOSYSTEM: '1',
};

function git(cwd: string, args: string[]): string {
  return execFileSync('git', args, {
    cwd,
    env: gitEnv,
    encoding: 'utf8',
  }).trim();
}

describe('GitWorktreeService custom worktree.root integration', () => {
  const dirs: string[] = [];

  afterEach(async () => {
    for (const dir of dirs.splice(0)) {
      await fs.rm(dir, { recursive: true, force: true });
    }
  });

  async function initRepo(): Promise<{ root: string; repo: string }> {
    const root = await fs.mkdtemp(path.join(os.tmpdir(), 'wt-custom-root-'));
    dirs.push(root);
    const repo = path.join(root, 'repo');
    await fs.mkdir(repo, { recursive: true });
    git(repo, ['init', '-b', 'main']);
    await fs.writeFile(path.join(repo, 'README.md'), 'hello\n');
    git(repo, ['add', 'README.md']);
    git(repo, ['commit', '-m', 'init']);
    return { root, repo };
  }

  it('creates, ignores, and removes a worktree under a custom worktree.root without touching legacy .qwen/.gitignore', async () => {
    const { repo } = await initRepo();
    await fs.mkdir(path.join(repo, '.qwen'), { recursive: true });
    const legacyGitignore = path.join(repo, '.qwen', '.gitignore');
    const legacyBody = `# Auto-generated by qwen-code.\n${WORKTREES_DIR}/\n`;
    await fs.writeFile(legacyGitignore, legacyBody);

    const service = new GitWorktreeService(repo, {
      worktreeRoot: '.worktrees',
    });
    const created = await service.createUserWorktree('feat-custom', 'main');
    expect(created.success).toBe(true);
    expect(created.worktree?.path).toBe(
      path.join(repo, '.worktrees', 'feat-custom'),
    );

    const excludeContent = await fs.readFile(
      path.join(repo, '.git', 'info', 'exclude'),
      'utf8',
    );
    // Custom roots add a per-checkout exclude entry, not a whole-directory rule.
    expect(excludeContent).toContain('/.worktrees/feat-custom/');
    expect(excludeContent).not.toContain('\n/.worktrees/\n');
    // Legacy .qwen/.gitignore must stay intact when custom root is in use,
    // while .worktrees/ itself must be ignored by .git/info/exclude.
    expect(await fs.readFile(legacyGitignore, 'utf8')).toBe(legacyBody);
    expect(git(repo, ['status', '--porcelain'])).not.toContain('.worktrees');

    const removed = await service.removeUserWorktree('feat-custom', {
      deleteBranch: true,
    });
    expect(removed.success).toBe(true);
    await expect(
      fs.access(path.join(repo, '.worktrees', 'feat-custom')),
    ).rejects.toThrow();
    const excludeAfterRemove = await fs.readFile(
      path.join(repo, '.git', 'info', 'exclude'),
      'utf8',
    );
    expect(excludeAfterRemove).not.toContain('/.worktrees/feat-custom/');
  });

  it('scopes custom-root info/exclude per checkout so pre-existing user files in the root dir stay visible to git (R1-7)', async () => {
    const { repo } = await initRepo();
    await fs.mkdir(path.join(repo, 'docs'), { recursive: true });
    await fs.writeFile(path.join(repo, 'docs', 'notes.md'), 'user note\n');

    const service = new GitWorktreeService(repo, { worktreeRoot: 'docs' });
    const created = await service.createUserWorktree('feat-doc', 'main');
    expect(created.success).toBe(true);

    const status = git(repo, [
      'status',
      '--porcelain',
      '--untracked-files=all',
    ]);
    expect(status).toContain('?? docs/notes.md');
    expect(status).not.toContain('docs/feat-doc');

    const removed = await service.removeUserWorktree('feat-doc', {
      deleteBranch: true,
    });
    expect(removed.success).toBe(true);
    const excludeAfter = await fs.readFile(
      path.join(repo, '.git', 'info', 'exclude'),
      'utf8',
    );
    expect(excludeAfter).not.toContain('/docs/feat-doc/');
  });

  it('detects linked worktrees structurally via isLinkedWorktree() regardless of root name (R1-1/R1-9)', async () => {
    const { repo } = await initRepo();
    const mainSvc = new GitWorktreeService(repo, { worktreeRoot: '.wt-a' });
    expect(await mainSvc.isLinkedWorktree()).toBe(false);

    const created = await mainSvc.createUserWorktree('old-root-wt', 'main');
    expect(created.success).toBe(true);
    const nestedDir = path.join(created.worktree!.path, 'sub');
    await fs.mkdir(nestedDir, { recursive: true });

    // Even when probed with a different configured root `.wt-b`, git reports
    // this checkout as a linked worktree.
    const probeOtherRoot = new GitWorktreeService(nestedDir, {
      worktreeRoot: '.wt-b',
    });
    expect(await probeOtherRoot.isLinkedWorktree()).toBe(true);
  });

  it.skipIf(process.platform === 'win32')(
    'isLinkedWorktree() handles repository paths containing a newline without false positives (R2-2)',
    async () => {
      const root = await fs.mkdtemp(path.join(os.tmpdir(), 'wt-nl-root-'));
      dirs.push(root);
      const nlRepo = path.join(root, 'repo\nline2');
      await fs.mkdir(nlRepo, { recursive: true });
      git(nlRepo, ['init', '-b', 'main']);
      await fs.writeFile(path.join(nlRepo, 'README.md'), 'hello\n');
      git(nlRepo, ['add', 'README.md']);
      git(nlRepo, ['commit', '-m', 'init']);

      const mainSvc = new GitWorktreeService(nlRepo, {
        worktreeRoot: '.worktrees',
      });
      expect(await mainSvc.isLinkedWorktree()).toBe(false);

      const created = await mainSvc.createUserWorktree('nl-wt', 'main');
      expect(created.success).toBe(true);
      const subDir = path.join(created.worktree!.path, 'nested');
      await fs.mkdir(subDir, { recursive: true });
      expect(
        await new GitWorktreeService(created.worktree!.path).isLinkedWorktree(),
      ).toBe(true);
      expect(await new GitWorktreeService(subDir).isLinkedWorktree()).toBe(
        true,
      );
    },
  );

  it('blocks symlinkDirectories entries that overlap the configured custom worktree.root', async () => {
    const { repo } = await initRepo();
    await fs.mkdir(path.join(repo, 'node_modules', 'pkg'), { recursive: true });
    await fs.mkdir(path.join(repo, 'tmp', 'cache'), { recursive: true });
    await fs.writeFile(path.join(repo, 'tmp', 'cache', 'x.txt'), 'ok');

    const service = new GitWorktreeService(repo, { worktreeRoot: 'tmp/wts' });
    const created = await service.createUserWorktree('sym-check', 'main', {
      symlinkDirectories: ['tmp', 'tmp/wts', 'tmp/cache', 'node_modules'],
    });
    expect(created.success).toBe(true);
    const wtPath = created.worktree!.path;

    // Ancestor `tmp` and exact `tmp/wts` must be refused to prevent recursion.
    const tmpStat = await fs.lstat(path.join(wtPath, 'tmp')).catch(() => null);
    expect(tmpStat?.isSymbolicLink() ?? false).toBe(false);
    await expect(fs.lstat(path.join(wtPath, 'tmp', 'wts'))).rejects.toThrow();

    // Unrelated sibling `tmp/cache` and `node_modules` are still symlinked.
    expect(
      (await fs.lstat(path.join(wtPath, 'tmp', 'cache'))).isSymbolicLink(),
    ).toBe(true);
    expect(
      (await fs.lstat(path.join(wtPath, 'node_modules'))).isSymbolicLink(),
    ).toBe(true);
  });

  it('rejects creating a worktree when custom worktree.root is a symlink escaping the repository', async () => {
    const { root, repo } = await initRepo();
    const outside = path.join(root, 'outside');
    await fs.mkdir(outside, { recursive: true });
    await fs.symlink(outside, path.join(repo, '.worktrees'));

    const service = new GitWorktreeService(repo, {
      worktreeRoot: '.worktrees',
    });
    const created = await service.createUserWorktree('escape-test', 'main');
    expect(created.success).toBe(false);
    expect(created.code).toBe('invalid_worktree_root');
    expect(await fs.readdir(outside)).toEqual([]);
  });

  it('sweeps stale agent worktrees under custom worktree.root and skips invalid roots', async () => {
    const { repo } = await initRepo();
    const service = new GitWorktreeService(repo, {
      worktreeRoot: '.worktrees',
    });
    const created = await service.createUserWorktree('agent-1234abc', 'main');
    expect(created.success).toBe(true);

    // Invalid root fails closed without touching the checkout.
    expect(
      await cleanupStaleAgentWorktrees(repo, {
        cutoffMs: -1,
        worktreeRoot: '../escape',
      }),
    ).toBe(0);
    await expect(fs.access(created.worktree!.path)).resolves.toBeUndefined();

    // Valid custom root cleans up the stale agent checkout.
    expect(
      await cleanupStaleAgentWorktrees(repo, {
        cutoffMs: -1,
        worktreeRoot: '.worktrees',
      }),
    ).toBe(1);
    await expect(fs.access(created.worktree!.path)).rejects.toThrow();
  });

  it('restores a worktree session sidecar under custom worktree.root and fails closed on invalid root without clearing sidecar', async () => {
    const { root, repo } = await initRepo();
    const service = new GitWorktreeService(repo, {
      worktreeRoot: '.worktrees',
    });
    const created = await service.createUserWorktree('resume-custom', 'main');
    expect(created.success).toBe(true);
    const sessionId = '11111111-1111-4111-8111-111111111111';
    await writeWorktreeSessionMarker(created.worktree!.path, sessionId);

    const sidecarPath = path.join(root, `${sessionId}.worktree.json`);
    await writeWorktreeSession(sidecarPath, {
      slug: 'resume-custom',
      worktreePath: created.worktree!.path,
      worktreeBranch: created.worktree!.branch,
      originalCwd: repo,
      originalBranch: 'main',
      originalHeadCommit: git(repo, ['rev-parse', 'HEAD']),
    });

    // Invalid worktree.root setting must NOT clear the sidecar and must surface
    // a visible WorktreeRestoreRefusedError (R1-10).
    const invalidWarnings: unknown[] = [];
    const invalidRestore = await restoreWorktreeContext(
      sidecarPath,
      (err) => invalidWarnings.push(err),
      sessionId,
      '../escape',
    );
    expect(invalidRestore.session).toBeNull();
    expect(invalidWarnings[0]).toBeInstanceOf(WorktreeRestoreRefusedError);
    expect(await readWorktreeSession(sidecarPath)).not.toBeNull();

    // Switching worktree.root to another valid root must also fail closed
    // WITHOUT destroying the prior managed checkout's sidecar (R1-5).
    const mismatchWarnings: unknown[] = [];
    const mismatchRestore = await restoreWorktreeContext(
      sidecarPath,
      (err) => mismatchWarnings.push(err),
      sessionId,
      '.other-wt',
    );
    expect(mismatchRestore.session).toBeNull();
    expect(mismatchWarnings[0]).toBeInstanceOf(WorktreeRestoreRefusedError);
    expect(await readWorktreeSession(sidecarPath)).not.toBeNull();

    // Valid custom worktree.root restores the session cleanly.
    const restored = await restoreWorktreeContext(
      sidecarPath,
      undefined,
      sessionId,
      '.worktrees',
    );
    expect(restored.session?.slug).toBe('resume-custom');
    expect(restored.contextMessage).toContain(created.worktree!.path);
  });

  it('matches custom-root session transcripts in SessionService only when worktreeRoot is supplied (R1-16)', async () => {
    const { root, repo } = await initRepo();
    const runtimeBaseDir = path.join(root, 'runtime');
    const sessionId = '22222222-2222-4222-8222-222222222222';
    const customCwd = path.join(repo, '.worktrees', 'wt-transcript');

    const storage = new Storage(repo, runtimeBaseDir);
    const chatsDir = path.join(storage.getProjectDir(), 'chats');
    await fs.mkdir(chatsDir, { recursive: true });
    await fs.writeFile(
      path.join(chatsDir, `${sessionId}.jsonl`),
      `${JSON.stringify({
        uuid: 'u1',
        parentUuid: null,
        sessionId,
        timestamp: '2026-11-28T00:00:00.000Z',
        type: 'user',
        cwd: customCwd,
        version: '0.0.0',
        message: { role: 'user', parts: [{ text: 'hello from custom wt' }] },
      })}\n`,
    );

    const withoutRoot = new SessionService(repo, { runtimeBaseDir });
    expect(await withoutRoot.getSessionLocation(sessionId)).toBeUndefined();

    const withCustomRoot = new SessionService(repo, {
      runtimeBaseDir,
      worktreeRoot: '.worktrees',
    });
    expect(await withCustomRoot.getSessionLocation(sessionId)).toBe('active');
    const listed = await withCustomRoot.listSessions();
    expect(listed.items.map((item) => item.sessionId)).toContain(sessionId);

    // R2-3: SessionReferenceService also resolves the custom-root transcript
    // only when configured with worktreeRoot.
    const refWithoutRoot = new SessionReferenceService(repo, {
      runtimeBaseDir,
    });
    expect(await refWithoutRoot.resolve(sessionId)).toEqual({
      notFound: true,
    });

    const refWithRoot = new SessionReferenceService(repo, {
      runtimeBaseDir,
      worktreeRoot: '.worktrees',
    });
    const resolvedRef = await refWithRoot.resolve(sessionId);
    expect('notFound' in resolvedRef).toBe(false);
    if (!('notFound' in resolvedRef)) {
      expect(resolvedRef.meta.sessionId).toBe(sessionId);
      expect(resolvedRef.text).toContain('hello from custom wt');
    }
  });
});
