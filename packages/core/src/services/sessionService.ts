  parentSessionId?: string;
  /** Immutable creator attribution read from `session_source`. */
  sourceType?: string;
  /** Optional source-specific identifier paired with `sourceType`. */
  sourceId?: string;
  /** True when the item was read from the archive directory. */
  isArchived?: boolean;
