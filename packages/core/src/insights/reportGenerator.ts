import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import type { AggregatedData, InsightResults } from './types.js';

/** 报告标题与页脚的品牌信息；由命令层按产品注入。 */
export interface ReportBranding {
  productName: string;
  footerLink?: string;
}

/**
 * Generates a self-contained HTML report file with inline CSS and JS.
 * No external CDN dependencies — works fully offline.
 */
export async function generateHtmlReport(
  aggregated: AggregatedData,
  insights: InsightResults,
  outputPath: string,
  branding: ReportBranding,
): Promise<void> {
  const html = buildHtml(aggregated, insights, branding);
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, html, 'utf-8');
}

function buildHtml(
  aggregated: AggregatedData,
  insights: InsightResults,
  branding: ReportBranding,
): string {
  const footerHtml = branding.footerLink
    ? ` • <a href="${branding.footerLink}">${escapeHtml(
        branding.footerLink.replace(/^https?:\/\//, ''),
      )}</a>`
    : '';
  const productName = escapeHtml(branding.productName);
  const dateRange = `${formatDate(aggregated.dateRange.start)} — ${formatDate(aggregated.dateRange.end)}`;
  const generatedAt = new Date().toLocaleString();

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${productName} Insights Report</title>
<style>
${getStyles()}
</style>
</head>
<body>
<div class="container">
  <header>
    <h1>🔍 ${productName} Insights Report</h1>
    <p class="subtitle">Generated: ${escapeHtml(generatedAt)} | Period: ${escapeHtml(dateRange)}</p>
  </header>

  <!-- At a Glance -->
  <section class="card at-a-glance">
    <h2>⚡ At a Glance</h2>
    <div class="glance-grid">
      <div class="glance-item glance-working">
        <h3>✅ What's Working</h3>
        <p>${escapeHtml(insights.atAGlance.whatsWorking)}</p>
      </div>
      <div class="glance-item glance-hindering">
        <h3>⚠️ What's Hindering</h3>
        <p>${escapeHtml(insights.atAGlance.whatsHindering)}</p>
      </div>
      <div class="glance-item glance-quickwins">
        <h3>🚀 Quick Wins</h3>
        <ul>
          ${insights.atAGlance.quickWins.map((w) => `<li>${escapeHtml(w)}</li>`).join('\n          ')}
        </ul>
      </div>
      <div class="glance-item glance-ambitious">
        <h3>🔮 Ambitious Workflows</h3>
        <ul>
          ${insights.atAGlance.ambitiousWorkflows.map((w) => `<li>${escapeHtml(w)}</li>`).join('\n          ')}
        </ul>
      </div>
    </div>
  </section>

  <!-- Summary -->
  <section class="card">
    <h2>📋 Summary</h2>
    <p>${escapeHtml(insights.summary)}</p>
  </section>

  <!-- Overview Cards -->
  <section class="stats-grid">
    <div class="stat-card">
      <div class="stat-value">${aggregated.totalSessions}</div>
      <div class="stat-label">Sessions</div>
    </div>
    <div class="stat-card">
      <div class="stat-value">${aggregated.totalMessages}</div>
      <div class="stat-label">Total Messages</div>
    </div>
    <div class="stat-card">
      <div class="stat-value">${aggregated.totalUserMessages}</div>
      <div class="stat-label">User Messages</div>
    </div>
    <div class="stat-card">
      <div class="stat-value">${Math.round(aggregated.totalMessages / Math.max(aggregated.totalSessions, 1))}</div>
      <div class="stat-label">Avg Messages/Session</div>
    </div>
  </section>

  <!-- Top Topics -->
  <section class="card">
    <h2>🏷️ Top Topics</h2>
    ${renderTopTopics(insights.topTopics)}
  </section>

  <!-- Top Languages -->
  <section class="card">
    <h2>💻 Languages</h2>
    ${renderLanguages(insights.topLanguages)}
  </section>

  <!-- Activity Patterns -->
  <section class="card">
    <h2>⏰ Activity Patterns</h2>
    <p>${escapeHtml(insights.activityPatterns)}</p>
    ${renderHourlyChart(aggregated.hourlyDistribution)}
  </section>

  <!-- Complexity Distribution -->
  <section class="card">
    <h2>📊 Task Complexity</h2>
    ${renderComplexity(aggregated.complexityDistribution)}
  </section>

  <!-- Trends -->
  <section class="card">
    <h2>📈 Trends</h2>
    <p>${escapeHtml(insights.trends)}</p>
  </section>

  <!-- Productivity Tips -->
  <section class="card">
    <h2>💡 Productivity Tips</h2>
    <ul class="tips-list">
      ${insights.productivityTips.map((tip) => `<li>${escapeHtml(tip)}</li>`).join('\n      ')}
    </ul>
  </section>

  <footer>
    <p>Generated by ${productName}${footerHtml}</p>
  </footer>
</div>
</body>
</html>`;
}

function renderTopTopics(
  topics: Array<{ name: string; count: number; description: string }>,
): string {
  if (topics.length === 0) return '<p class="empty">No topics detected.</p>';
  const maxCount = Math.max(...topics.map((t) => t.count), 1);
  return `<div class="bar-chart">
    ${topics
      .map(
        (t) => `<div class="bar-row">
      <div class="bar-label">${escapeHtml(t.name)}</div>
      <div class="bar-container">
        <div class="bar" style="width: ${(t.count / maxCount) * 100}%"></div>
        <span class="bar-value">${t.count}</span>
      </div>
      <div class="bar-description">${escapeHtml(t.description)}</div>
    </div>`,
      )
      .join('\n    ')}
  </div>`;
}

function renderLanguages(
  languages: Array<{ name: string; count: number; percentage: number }>,
): string {
  if (languages.length === 0)
    return '<p class="empty">No languages detected.</p>';
  const maxCount = Math.max(...languages.map((l) => l.count), 1);
  return `<div class="bar-chart">
    ${languages
      .map(
        (l) => `<div class="bar-row">
      <div class="bar-label">${escapeHtml(l.name)}</div>
      <div class="bar-container">
        <div class="bar bar-lang" style="width: ${(l.count / maxCount) * 100}%"></div>
        <span class="bar-value">${l.percentage}%</span>
      </div>
    </div>`,
      )
      .join('\n    ')}
  </div>`;
}

function renderHourlyChart(distribution: number[]): string {
  const max = Math.max(...distribution, 1);
  const bars = distribution
    .map(
      (count, hour) =>
        `<div class="hourly-bar" title="${String(hour).padStart(2, '0')}:00 — ${count} sessions">
        <div class="hourly-fill" style="height: ${(count / max) * 100}%"></div>
        <div class="hourly-label">${hour % 6 === 0 ? String(hour).padStart(2, '0') : ''}</div>
      </div>`,
    )
    .join('\n      ');
  return `<div class="hourly-chart">
      ${bars}
    </div>`;
}

function renderComplexity(distribution: {
  low: number;
  medium: number;
  high: number;
}): string {
  const total = distribution.low + distribution.medium + distribution.high;
  if (total === 0) return '<p class="empty">No data.</p>';
  const pLow = Math.round((distribution.low / total) * 100);
  const pMed = Math.round((distribution.medium / total) * 100);
  const pHigh = Math.round((distribution.high / total) * 100);
  return `<div class="complexity-bar">
    <div class="complexity-segment complexity-low" style="width: ${pLow}%" title="Low: ${distribution.low}">Low ${pLow}%</div>
    <div class="complexity-segment complexity-medium" style="width: ${pMed}%" title="Medium: ${distribution.medium}">Med ${pMed}%</div>
    <div class="complexity-segment complexity-high" style="width: ${pHigh}%" title="High: ${distribution.high}">High ${pHigh}%</div>
  </div>`;
}

