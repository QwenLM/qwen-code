/**
 * XML tag names for task notifications (background task completions / stalls).
 */
/** XML tag for skill/command name in user messages. */
export const COMMAND_NAME_TAG = 'command-name';
export const COMMAND_MESSAGE_TAG = 'command-message';
export const COMMAND_ARGS_TAG = 'command-args';
export const BASH_INPUT_TAG = 'bash-input';
export const SKILL_FORMAT_TAG = 'skill-format';
/** Caveat tag prepended to slash-command skill output. */
export const LOCAL_COMMAND_CAVEAT_TAG = 'local-command-caveat';
/** Tag wrapping local slash-command output in user transcript messages. */
export const LOCAL_COMMAND_STDOUT_TAG = 'local-command-stdout';

/**
 * Formats a user-invoked slash command for transcript storage and SDK replay.
 */
export function buildSlashCommandMetadata(
  commandName: string,
  args?: string,
): string {
  const parts = [
    `<${COMMAND_MESSAGE_TAG}>${commandName}</${COMMAND_MESSAGE_TAG}>`,
    `<${COMMAND_NAME_TAG}>/${commandName}</${COMMAND_NAME_TAG}>`,
  ];
  if (args) {
    parts.push(`<${COMMAND_ARGS_TAG}>${args}</${COMMAND_ARGS_TAG}>`);
  }
  return parts.join('\n');
}

/** Pre-built caveat message for slash-command skill activations. */
export const LOCAL_COMMAND_CAVEAT = `<${LOCAL_COMMAND_CAVEAT_TAG}>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</${LOCAL_COMMAND_CAVEAT_TAG}>`;

export const TASK_NOTIFICATION_TAG = 'task-notification';
export const TASK_ID_TAG = 'task-id';
export const TOOL_USE_ID_TAG = 'tool-use-id';
export const OUTPUT_FILE_TAG = 'output-file';
export const STATUS_TAG = 'status';
export const SUMMARY_TAG = 'summary';

/**
 * Prefix used in completion summary strings so the model can identify
 * background bash completions (vs monitor or other task types).
 */
export const BACKGROUND_BASH_SUMMARY_PREFIX = 'Background command ';

// ============================================================================
// XML escaping
// ============================================================================

/**
 * Escape XML/HTML special characters for safe interpolation into element
 * text content (between tags).
 */
export function escapeXml(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

/**
 * Unescape XML/HTML entities back to their literal characters.
 */
export function unescapeXml(s: string): string {
  return s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
}
