/**
 * @fileoverview Memory extraction directive for fork subagents.
 *
 * The fork inherits the parent system prompt and message history for
 * prompt-cache alignment; this string is passed as the fork's initial user
 * directive. The fork terminates naturally when the model produces an
 * assistant message with no tool calls — no complete_task signal required.
 *
 * The prompt structure uses a strict
 * opener that scopes the fork to the last N messages, a rich 4-type
 * taxonomy with per-type when/how/body-structure/examples, a NOT-TO-SAVE
 * section with an explicit-save escape clause, and a two-step save
 * procedure (file + MEMORY.md index).
 */

import * as path from 'node:path';
import type { MemoryScope } from '../memory/structured-memory-store.js';

/** A single memory root the extraction fork can write to. */
export interface MemoryExtractionRoot {
  scope: MemoryScope;
  /** Absolute path to the memory directory. */
  dir: string;
  /** Existing MEMORY.md index content for this root (may be empty). */
  index: string;
  /** Existing memory file names in this root (excludes MEMORY.md). */
  files: string[];
}

export interface PreviousGeneratedMemory {
  /** Absolute path written by the previous incremental extraction. */
  filePath: string;
  /** Full file content captured after that extraction committed. */
  content: string;
}

/**
 * Builds the directive for the independent-model incremental strategy.
 * Conversation evidence is supplied separately as the raw transcript slice;
 * this directive supplies only the previous committed memory snapshot.
 */
export function buildIndependentIncrementalMemoryDirective(
  roots: readonly MemoryExtractionRoot[],
  incrementalMessageCount: number,
  previousGeneratedMemories: readonly PreviousGeneratedMemory[],
): string {
  const multiRoot = roots.length > 1;
  const previousByRoot = roots.map((root) => ({
    ...root,
    files: [
      ...new Set([
        ...root.files,
        ...previousGeneratedMemories
          .filter(({ filePath }) => {
            const relative = path.relative(root.dir, filePath);
            return (
              relative !== '' &&
              !relative.startsWith('..') &&
              !path.isAbsolute(relative)
            );
          })
          .map(({ filePath }) => path.basename(filePath)),
      ]),
    ],
  }));
  const previousMemoryBlock =
    previousGeneratedMemories.length === 0
      ? 'No memory content was generated by the previous committed extraction.'
      : previousGeneratedMemories
          .map(
            ({ filePath, content }, index) =>
              [
                `<previous-generated-memory index="${index + 1}" path="${filePath}">`,
                content,
                '</previous-generated-memory>',
              ].join('\n'),
          )
          .join('\n\n');

  const dirList = multiRoot
    ? previousByRoot
        .map((root) => `${root.scope} scope: ${root.dir}`)
        .join('; ')
    : (previousByRoot[0]?.dir ?? '');
  const manifests = previousByRoot
    .filter((root) => root.files.length > 0)
    .map((root) => {
      const scopeSuffix = multiRoot ? ` (${root.scope} scope)` : '';
      return [
        `## Existing memory files${scopeSuffix}`,
        '',
        ...root.files.map((file) => `- ${file}`),
      ].join('\n');
    });
  const currentIndexes = previousByRoot
    .filter((root) => root.index)
    .map((root) => {
      const scopeSuffix = multiRoot ? ` (${root.scope} scope)` : '';
      return `## Current MEMORY.md${scopeSuffix}\n\n${root.index}`;
    });

  const memoryTypes = [
    '## Memory types',
    '',
    '- `user`: durable information about the user\'s role, goals, knowledge, or preferences.',
    '- `feedback`: reusable guidance about how to collaborate, including corrections and validated non-obvious approaches. Include the rule, **Why:**, and **How to apply:**.',
    '- `project`: non-derivable project context, decisions, ownership, motivation, or deadlines. Convert relative dates to absolute dates and include **Why:** and **How to apply:**.',
    '- `reference`: a pointer to an external resource and why or when it should be used.',
  ].join('\n');

  const exclusions = [
    '## Do not save',
    '',
    '- Code patterns, architecture, file paths, project structure, git history, or facts already documented in AGENTS.md.',
    '- Debugging recipes or information that can be recovered from the current code or git history.',
    '- Ephemeral task state, including files changed, branch/commit/push status, temporary errors, retries, current progress, or whether tests, builds, and typechecks passed.',
    '- Duplicate memories or content that is only useful for the current conversation.',
    '',
    'These exclusions still apply when the user explicitly asks to remember the excluded content.',
  ].join('\n');

  const saveFormat = [
    '## Save format',
    '',
    'Write each memory to a kebab-case Markdown file with frontmatter fields `name`, `description`, and `metadata.type`.',
    'For each created, updated, or removed memory, update the corresponding `MEMORY.md` index in the same write batch.',
    'Each index entry must be one concise line: `- [Title](file.md) — one-line hook`. Keep the index under 200 lines and do not put memory content directly in it.',
    'Prefer updating an existing topic file over creating a duplicate. Creating zero memories is normal.',
  ].join('\n');

  return [
    '## Independent incremental memory extraction',
    '',
    `The conversation context contains exactly ${incrementalMessageCount} raw transcript messages after the previous committed cursor.`,
    'Use every supplied message as-is, including assistant tool calls and their tool results. Do not omit or reconstruct messages.',
    'Use the previous-generated-memory snapshot below when deciding whether to update, merge, or retain earlier memory content.',
    'Do not read or write outside the listed memory directories.',
    '',
    `Available tools: Read and Edit/Write for paths inside the listed memory director${multiRoot ? 'ies' : 'y'} only (${dirList}).`,
    '',
    '## Shortest execution path',
    '',
    'First decide the complete set of durable changes from the transcript, current indexes, manifests, and previous-generated-memory snapshot.',
    '- No durable change: call no tools and finish immediately.',
    '- Only new memory files or index-only changes: skip Read and issue every required Write in one parallel tool batch immediately.',
    '- Existing memory content must be inspected or updated: issue every necessary Read in one parallel tool batch, then issue every required Write/Edit in one parallel tool batch on the next response.',
    '',
    'The current MEMORY.md indexes are already included below. Never Read MEMORY.md. When changing an index, use its supplied content to write the complete updated index.',
    'Read only existing memory files whose full content is required and is not already supplied below. New files never need a prior Read. Do not read every file in a manifest.',
    'Combine all changes to the same file into one Write/Edit. After the write batch succeeds, stop calling tools and finish with one brief sentence. Do not reread or make another write pass unless a tool call failed.',
    '',
    memoryTypes,
    '',
    exclusions,
    '',
    saveFormat,
    ...(roots.length > 0 ? ['', buildScopeRoutingBlock(previousByRoot)] : []),
    ...(manifests.length > 0 ? ['', ...manifests] : []),
    ...(currentIndexes.length > 0 ? ['', ...currentIndexes] : []),
    '',
    '## Previous generated memory snapshot',
    '',
    previousMemoryBlock,
  ].join('\n');
}

/**
 * Scope-routing guidance for the dual-root case, rendered only when more than
 * one root is active. Mirrors the system-prompt routing in auto-memory-prompt
 * (memory-design doc §2): two types pinned, two floating by cross-project
 * applicability. The pinned types are additionally enforced at the Write/Edit
 * tool layer, so this also warns the model that misrouting is rejected.
 */
function buildScopeRoutingBlock(roots: readonly MemoryExtractionRoot[]): string {
  if (roots.length === 1) {
    const activeScope = roots[0].scope;
    const inactiveScope = activeScope === 'user' ? 'project' : 'user';
    const floatingGuidance =
      activeScope === 'user'
        ? 'Save `feedback` or `reference` only when it applies across projects.'
        : 'Save `feedback` or `reference` only when it is specific to this project.';
    return [
      `## Active memory scope: ${activeScope.toUpperCase()}`,
      '',
      `Only the **${activeScope.toUpperCase()} scope** is enabled: \`${roots[0].dir}/\`.`,
      `Do not save \`type: ${inactiveScope}\` memories while the ${inactiveScope.toUpperCase()} scope is disabled.`,
      floatingGuidance,
    ].join('\n');
  }

  const userDir = roots.find((r) => r.scope === 'user')?.dir;
  const projectDir = roots.find((r) => r.scope === 'project')?.dir;
  return [
    '## Where to save: USER scope vs PROJECT scope',
    '',
    'You have two memory directories. Choose by one question: *is this fact true across all of this user’s projects, or only this project?*',
    '',
    `- **USER scope** (shared across all projects): \`${userDir}/\``,
    `- **PROJECT scope** (only this project): \`${projectDir}/\``,
    '',
    'Routing by type:',
    '- `user` → **always USER**.',
    '- `project` → **always PROJECT**.',
    '- `feedback` → default **USER** (personal collaboration style); use PROJECT only for a rule everyone working on this project must follow.',
    '- `reference` → default **PROJECT** (this project’s dashboards/boards/docs); use USER only for a user-level resource (e.g. a company-wide wiki).',
    '',
    'Write each file into the directory you chose, and add its pointer line to the `MEMORY.md` index *in that same directory*. The pinned types are enforced — saving a `type: user` file into the PROJECT directory (or `type: project` into USER) will be rejected, so route them correctly.',
  ].join('\n');
}

/**
 * Builds the memory-extraction directive (user message) for the fork. Accepts
 * one independently enabled root or both USER + PROJECT roots.
 */
export function buildMemoryExtractionDirective(
  roots: readonly MemoryExtractionRoot[],
  newMessageCount: number,
): string {
  const multiRoot = roots.length > 1;

  const buildManifest = (files: string[], heading: string): string =>
    files.length > 0
      ? `\n\n${heading}\n\n${files.map((f) => `- ${f}`).join('\n')}\n\nCheck this list before writing — update an existing file rather than creating a duplicate.`
      : '';

  const dirList = multiRoot
    ? roots.map((r) => `${r.scope} scope: ${r.dir}`).join('; ')
    : (roots[0]?.dir ?? '');

  const manifest = multiRoot
    ? roots
        .map((r) =>
          buildManifest(r.files, `## Existing memory files (${r.scope} scope)`),
        )
        .join('')
    : buildManifest(roots[0]?.files ?? [], '## Existing memory files');

  const opener = [
    `You are now acting as the memory extraction subagent. Analyze the most recent ~${newMessageCount} messages above and use them to update your persistent memory system.`,
    '',
    `Available tools: Read, Grep, Glob, and Edit/Write for paths inside the memory director${multiRoot ? 'ies' : 'y'} only (${dirList}). All other tools will be denied.`,
    '',
    `You have a limited turn budget. Edit requires a prior Read of the same file, so the efficient strategy is: turn 1 — issue all Read calls in parallel for every file you might update; turn 2 — issue all Write/Edit calls in parallel. Do not interleave reads and writes across multiple turns.`,
    '',
    `You MUST only use content from the last ~${newMessageCount} messages to update your persistent memories. Do not waste any turns attempting to investigate or verify that content further — no grepping source files, no reading code to confirm a pattern exists, no git commands.${manifest}`,
  ].join('\n');

  const types = [
    '## Types of memory',
    '',
    'There are several discrete types of memory that you can store in your memory system:',
    '',
    '<types>',
    '<type>',
    '    <name>user</name>',
    "    <description>Contain information about the user's role, goals, responsibilities, and knowledge. Great user memories help you tailor your future behavior to the user's preferences and perspective. Your goal in reading and writing these memories is to build up an understanding of who the user is and how you can be most helpful to them specifically. For example, you should collaborate with a senior software engineer differently than a student who is coding for the very first time. Keep in mind, that the aim here is to be helpful to the user. Avoid writing memories about the user that could be viewed as a negative judgement or that are not relevant to the work you're trying to accomplish together.</description>",
    "    <when_to_save>When you learn any details about the user's role, preferences, responsibilities, or knowledge</when_to_save>",
    "    <how_to_use>When your work should be informed by the user's profile or perspective. For example, if the user is asking you to explain a part of the code, you should answer that question in a way that is tailored to the specific details that they will find most valuable or that helps them build their mental model in relation to domain knowledge they already have.</how_to_use>",
    '    <examples>',
    "    user: I'm a data scientist investigating what logging we have in place",
    '    assistant: [saves user memory: user is a data scientist, currently focused on observability/logging]',
    '',
    "    user: I've been writing Go for ten years but this is my first time touching the React side of this repo",
    "    assistant: [saves user memory: deep Go expertise, new to React and this project's frontend — frame frontend explanations in terms of backend analogues]",
    '    </examples>',
    '</type>',
    '<type>',
    '    <name>feedback</name>',
    '    <description>Guidance the user has given you about how to approach work — both what to avoid and what to keep doing. These are a very important type of memory to read and write as they allow you to remain coherent and responsive to the way you should approach work in the project. Record from failure AND success: if you only save corrections, you will avoid past mistakes but drift away from approaches the user has already validated, and may grow overly cautious.</description>',
    '    <when_to_save>Any time the user corrects your approach ("no not that", "don\'t", "stop doing X") OR confirms a non-obvious approach worked ("yes exactly", "perfect, keep doing that", accepting an unusual choice without pushback). Corrections are easy to notice; confirmations are quieter — watch for them. In both cases, save what is applicable to future conversations, especially if surprising or not obvious from the code. Include *why* so you can judge edge cases later.</when_to_save>',
    '    <how_to_use>Let these memories guide your behavior so that the user does not need to offer the same guidance twice.</how_to_use>',
    '    <body_structure>Lead with the rule itself, then a **Why:** line (the reason the user gave — often a past incident or strong preference) and a **How to apply:** line (when/where this guidance kicks in). Knowing *why* lets you judge edge cases instead of blindly following the rule.</body_structure>',
    '    <examples>',
    "    user: don't mock the database in these tests — we got burned last quarter when mocked tests passed but the prod migration failed",
    '    assistant: [saves feedback memory: integration tests must hit a real database, not mocks. Reason: prior incident where mock/prod divergence masked a broken migration]',
    '',
    '    user: stop summarizing what you just did at the end of every response, I can read the diff',
    '    assistant: [saves feedback memory: this user wants terse responses with no trailing summaries]',
    '',
    "    user: yeah the single bundled PR was the right call here, splitting this one would've just been churn",
    '    assistant: [saves feedback memory: for refactors in this area, user prefers one bundled PR over many small ones. Confirmed after I chose this approach — a validated judgment call, not a correction]',
    '    </examples>',
    '</type>',
    '<type>',
    '    <name>project</name>',
    '    <description>Information that you learn about ongoing work, goals, initiatives, bugs, or incidents within the project that is not otherwise derivable from the code or git history. Project memories help you understand the broader context and motivation behind the work the user is doing within this working directory.</description>',
    '    <when_to_save>When you learn who is doing what, why, or by when. These states change relatively quickly so try to keep your understanding of this up to date. Always convert relative dates in user messages to absolute dates when saving (e.g., "Thursday" → "2026-03-05"), so the memory remains interpretable after time passes.</when_to_save>',
    "    <how_to_use>Use these memories to more fully understand the details and nuance behind the user's request and make better informed suggestions.</how_to_use>",
    '    <body_structure>Lead with the fact or decision, then a **Why:** line (the motivation — often a constraint, deadline, or stakeholder ask) and a **How to apply:** line (how this should shape your suggestions). Project memories decay fast, so the why helps future-you judge whether the memory is still load-bearing.</body_structure>',
    '    <examples>',
    "    user: we're freezing all non-critical merges after Thursday — mobile team is cutting a release branch",
    '    assistant: [saves project memory: merge freeze begins 2026-03-05 for mobile release cut. Flag any non-critical PR work scheduled after that date]',
    '',
    "    user: the reason we're ripping out the old auth middleware is that legal flagged it for storing session tokens in a way that doesn't meet the new compliance requirements",
    '    assistant: [saves project memory: auth middleware rewrite is driven by legal/compliance requirements around session token storage, not tech-debt cleanup — scope decisions should favor compliance over ergonomics]',
    '    </examples>',
    '</type>',
    '<type>',
    '    <name>reference</name>',
    '    <description>Stores pointers to where information can be found in external systems. These memories allow you to remember where to look to find up-to-date information outside of the project directory.</description>',
    '    <when_to_save>When you learn about resources in external systems and their purpose. For example, that bugs are tracked in a specific project in Linear or that feedback can be found in a specific Slack channel.</when_to_save>',
    '    <how_to_use>When the user references an external system or information that may be in an external system.</how_to_use>',
    '    <examples>',
    '    user: check the Linear project "INGEST" if you want context on these tickets, that\'s where we track all pipeline bugs',
    '    assistant: [saves reference memory: pipeline bugs are tracked in Linear project "INGEST"]',
    '',
    "    user: the Grafana board at grafana.internal/d/api-latency is what oncall watches — if you're touching request handling, that's the thing that'll page someone",
    '    assistant: [saves reference memory: grafana.internal/d/api-latency is the oncall latency dashboard — check it when editing request-path code]',
    '    </examples>',
    '</type>',
    '</types>',
  ].join('\n');

  const whatNotToSave = [
    '## What NOT to save in memory',
    '',
    '- Code patterns, conventions, architecture, file paths, or project structure — these can be derived by reading the current project state.',
    '- Git history, recent changes, or who-changed-what — `git log` / `git blame` are authoritative.',
    '- Debugging solutions or fix recipes — the fix is in the code; the commit message has the context.',
    '- Anything already documented in AGENTS.md files.',
    '- Ephemeral task details: in-progress work, temporary state, current conversation context.',
    '',
    'These exclusions apply even when the user explicitly asks you to save. If they ask you to save a PR list or activity summary, ask what was *surprising* or *non-obvious* about it — that is the part worth keeping.',
  ].join('\n');

  const howToSave = [
    '## How to save memories',
    '',
    'Saving a memory is a two-step process:',
    '',
    '**Step 1** — write the memory to its own file (kebab-case filename, e.g., `user-role.md`, `feedback-testing.md`) using this frontmatter format:',
    '',
    '```markdown',
    '---',
    'name: {{short-kebab-case-slug}}',
    'description: {{one-line summary — used to decide relevance in future conversations, so be specific}}',
    'metadata:',
    '  type: {{user, feedback, project, reference}}',
    '---',
    '',
    '{{memory content — for feedback/project types, structure as: rule/fact, then **Why:** and **How to apply:** lines. Link related memories with [[their-name]].}}',
    '```',
    '',
    '**Step 2** — add a pointer to that file in `MEMORY.md`. `MEMORY.md` is an index, not a memory — each entry should be one line, under ~150 characters: `- [Title](file.md) — one-line hook`. It has no frontmatter. Never write memory content directly into `MEMORY.md`.',
    '',
    '- `MEMORY.md` is always loaded into the main agent context — lines after 200 will be truncated, so keep the index concise',
    '- Keep the name, description, and type fields in memory files up-to-date with the content',
    '- Organize memory semantically by topic, not chronologically',
    '- Update or remove memories that turn out to be wrong or outdated',
    '- Do not write duplicate memories. First check if there is an existing memory you can update before writing a new one.',
    '- If `MEMORY.md` references a file that no longer exists (deleted out-of-band), drop the line as part of your edit.',
    '- Creating 0 memories is a normal outcome.',
  ].join('\n');

  const completion =
    'When you have no more writes to do, finish with a brief plain-text summary sentence (no tool calls). Do not call any completion or signalling tool — the fork terminates when you stop calling tools.';

  const parts: string[] = [
    opener,
    '',
    'If the user explicitly asks you to remember something, save it immediately as whichever type fits best. If they ask you to forget something, find and remove the relevant entry.',
    '',
    types,
    '',
    whatNotToSave,
    '',
    howToSave,
  ];

  if (roots.length > 0) {
    parts.push('', buildScopeRoutingBlock(roots));
  }

  parts.push('', completion);

  if (multiRoot) {
    for (const root of roots) {
      if (root.index) {
        parts.push(
          '',
          `## Current MEMORY.md (${root.scope} scope)\n\n${root.index}`,
        );
      }
    }
  } else if (roots[0]?.index) {
    parts.push('', `## Current MEMORY.md\n\n${roots[0].index}`);
  }

  return parts.join('\n');
}
