export function useManagedDiagnosticsText() {
  const { language } = useI18n();
  return (key: keyof typeof messages) =>
    language === 'ar'
      ? arMessages[key]
      : messages[key][
          language === 'zh-TW'
            ? 2
            : language === 'zh-CN'
              ? 1
              : language === 'ru'
                ? 3
                : 0
        ];
}
