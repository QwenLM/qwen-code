#!/usr/bin/env node
// Regenerate `client/components/managed/generated/managed-agent-api.ts` from
// the Managed Agent OpenAPI owned by packages/sdk-java/managed-agent-server:
//
//   npm run generate:managed-agent-api --workspace=@qwen-code/web-shell
//
// Only WebShell operations are generated, and planned operations, parameters
// and properties are removed first: the contract says planned surface must not
// reach a production client before the server implements it.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const SPEC = new URL(
  '../../sdk-java/managed-agent-server/src/main/resources/openapi/managed-agent-public-api.openapi.json',
  import.meta.url,
);
export const OUTPUT = new URL(
  '../client/components/managed/generated/managed-agent-api.ts',
  import.meta.url,
);
const STATUS = 'x-qwen-implementation-status';
const HEADER = `// Generated by packages/web-shell/scripts/generate-managed-agent-api.mjs.
// Do not edit; run \`npm run generate:managed-agent-api\` in packages/web-shell.
`;

export function webShellContract(spec) {
  const paths = {};
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const [method, operation] of Object.entries(item)) {
      if (operation.tags?.includes('WebShell') && !isPlanned(operation)) {
        (paths[path] ??= {})[method] = operation;
      }
    }
  }
  const contract = withoutPlanned({ ...spec, paths });
  const reachable = new Set();
  const visit = (node) => {
    if (Array.isArray(node)) {
      node.forEach(visit);
      return;
    }
    if (node === null || typeof node !== 'object') return;
    const ref = node.$ref;
    if (typeof ref === 'string' && !reachable.has(ref)) {
      reachable.add(ref);
      visit(resolve(contract, ref));
    }
    Object.values(node).forEach(visit);
  };
  visit(contract.paths);
  for (const [kind, entries] of Object.entries(contract.components)) {
    for (const name of Object.keys(entries)) {
      if (!reachable.has(`#/components/${kind}/${name}`)) {
        delete entries[name];
      }
    }
  }
  return contract;
}

export async function renderManagedAgentApi() {
  const spec = JSON.parse(await readFile(SPEC, 'utf8'));
  const ast = await openapiTS(webShellContract(spec), {
    defaultNonNullable: false,
  });
  return HEADER + astToString(ast);
}

function isPlanned(node) {
  return node?.[STATUS] === 'planned';
}

function withoutPlanned(node) {
  if (Array.isArray(node)) {
    return node.filter((entry) => !isPlanned(entry)).map(withoutPlanned);
  }
  if (node === null || typeof node !== 'object') return node;
  const copy = {};
  for (const [key, value] of Object.entries(node)) {
    copy[key] =
      key === 'properties'
        ? Object.fromEntries(
            Object.entries(value)
              .filter(([, schema]) => !isPlanned(schema))
              .map(([name, schema]) => [name, withoutPlanned(schema)]),
          )
        : withoutPlanned(value);
  }
  if (copy.properties && Array.isArray(copy.required)) {
    copy.required = copy.required.filter((name) => name in copy.properties);
  }
  return copy;
}

function resolve(spec, ref) {
  return ref
    .slice(2)
    .split('/')
    .reduce(
      (node, segment) =>
        node?.[segment.replaceAll('~1', '/').replaceAll('~0', '~')],
      spec,
    );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(OUTPUT, await renderManagedAgentApi());
}
