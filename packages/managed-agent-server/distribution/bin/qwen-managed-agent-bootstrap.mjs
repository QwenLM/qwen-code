#!/usr/bin/env node
/* global console, process */

/**
 * Generates the shared credentials for one Managed Agent deployment.
 *
 * The capability digest is an arbitrary shared identifier, not a hash of the
 * Harness capability set: the Harness echoes whatever value both sides were
 * given, so a random digest is valid.
 *
 * With --service-user, run as root: the files then get the owners and modes
 * the systemd layout uses, and server.env records the account for preflight.
 */

import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { realpathSync } from 'node:fs';
import {
  access,
  chmod,
  chown,
  lstat,
  mkdir,
  open,
  readlink,
  rename,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const TOKEN_BYTES = 32;
const KEY_BYTES = 32;
const DEFAULT_KEY_ID = 'reference-v1';
const FILE_MODE = 0o600;
const DIRECTORY_MODE = 0o700;
// systemd reads server.env as root; the group lets the account run --check.
const GROUP_FILE_MODE = 0o640;
const GROUP_DIRECTORY_MODE = 0o750;
// It is written unquoted into server.env, so keep to the portable user names.
const SERVICE_USER = /^[a-z_][a-z0-9_-]{0,31}$/;
// Linux's limit on symbolic links followed in one path lookup.
const MAX_SYMBOLIC_LINKS = 40;

export function generateSecrets(keyId = DEFAULT_KEY_ID) {
  return Object.freeze({
    token: randomBytes(TOKEN_BYTES).toString('hex'),
    digest: `sha256:${randomBytes(TOKEN_BYTES).toString('hex')}`,
    brokerToken: randomBytes(TOKEN_BYTES).toString('hex'),
    credentialKey: randomBytes(KEY_BYTES).toString('base64'),
    databasePassword: randomBytes(TOKEN_BYTES).toString('hex'),
    keyId,
  });
}

export function renderHarnessEnv(secrets) {
  return [
    '# Generated by qwen-managed-agent-bootstrap.',
    '# server.env points QWEN_MANAGED_AGENT_HARNESS_CREDENTIALS_FILE here.',
    `QWEN_SERVER_TOKEN=${secrets.token}`,
    `QWEN_HOSTED_HARNESS_CAPABILITY_DIGEST=${secrets.digest}`,
    '# The Runtime Broker. The Harness dials it only for tool-path Sessions,',
    '# and the control plane reads the same token from this file.',
    'QWEN_MANAGED_RUNTIME_BROKER_URL=http://127.0.0.1:4182',
    `QWEN_MANAGED_RUNTIME_BROKER_TOKEN=${secrets.brokerToken}`,
    '',
  ].join('\n');
}

export function renderServerEnv({
  databasePassword,
  applicationConfigPath,
  harnessEnvPath,
  serviceUser,
}) {
  return [
    '# Generated by qwen-managed-agent-bootstrap.',
    '# mysql-setup.sql creates this database account.',
    'SPRING_DATASOURCE_URL=jdbc:mysql://127.0.0.1:3306/qwen_managed_agent',
    'SPRING_DATASOURCE_USERNAME=qwen',
    `SPRING_DATASOURCE_PASSWORD=${databasePassword}`,
    'QWEN_MANAGED_AGENT_HARNESS_ENABLED=true',
    'QWEN_MANAGED_AGENT_HARNESS_BASE_URL=http://127.0.0.1:4170',
    '# The control plane reads the Harness token and digest from harness.env.',
    `QWEN_MANAGED_AGENT_HARNESS_CREDENTIALS_FILE='${harnessEnvPath}'`,
    '# The Session Store workspace ID derives from this existing directory.',
    'QWEN_MANAGED_AGENT_WORKSPACE_CWD=/srv/qwen-workspace',
    `SPRING_CONFIG_ADDITIONAL_LOCATION='file:${applicationConfigPath}'`,
    ...(serviceUser
      ? [
          '# Preflight checks file access as this account.',
          `QWEN_MANAGED_AGENT_SERVICE_USER=${serviceUser}`,
        ]
      : []),
    '',
  ].join('\n');
}

export function renderMysqlSetup(secrets) {
  const accounts = ["'qwen'@'localhost'", "'qwen'@'127.0.0.1'"];
  return [
    '-- Generated by qwen-managed-agent-bootstrap. Run it once as a MySQL',
    '-- administrator, for example `mysql -u root < mysql-setup.sql`, then delete',
    '-- it: server.env keeps the password. It stops at the first statement that',
    '-- fails, such as an existing database or account.',
    "-- A server with skip-name-resolve, the official images' default, matches a",
    "-- TCP client from 127.0.0.1 only against '127.0.0.1', so both hosts get an",
    '-- account. A MySQL in a container sees the gateway address instead; create',
    '-- the account for that host.',
    'CREATE DATABASE qwen_managed_agent CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;',
    ...accounts.map(
      (account) =>
        `CREATE USER ${account} IDENTIFIED BY '${secrets.databasePassword}';`,
    ),
    ...accounts.map(
      (account) => `GRANT ALL ON qwen_managed_agent.* TO ${account};`,
    ),
    "-- Flyway's boot probe reads this table; without it startup stops.",
    ...accounts.map(
      (account) =>
        `GRANT SELECT ON performance_schema.user_variables_by_thread TO ${account};`,
    ),
    '',
  ].join('\n');
}

export function renderApplicationYml(secrets) {
  return [
    '# Generated by qwen-managed-agent-bootstrap.',
    'qwen:',
    '  managed-agent:',
    '    runtime-broker:',
    `      credential-key-id: ${yamlSingleQuoted(secrets.keyId)}`,
    `      credential-key: ${yamlSingleQuoted(secrets.credentialKey)}`,
    '',
  ].join('\n');
}

function yamlSingleQuoted(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

async function exists(file) {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

// Sets the owner before the rename, so the file never appears with another.
async function writeAtomic(file, content, { mode = FILE_MODE, owner } = {}) {
  const temporary = `${file}.tmp-${randomBytes(4).toString('hex')}`;
  await writeFile(temporary, content, { mode: FILE_MODE });
  if (owner) {
    await chown(temporary, owner.uid, owner.gid);
  }
  await chmod(temporary, mode);
  await rename(temporary, file);
}

function idNumbers(flag, user) {
  return execFileSync('id', [flag, user], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  })
    .trim()
    .split(/\s+/)
    .map(Number);
}

// Returns an error message, or the account's uid, primary gid and groups.
export function lookupServiceUser(name, { lookup = idNumbers, uid } = {}) {
  if (!SERVICE_USER.test(name)) {
    return {
      error: `--service-user must be a user name such as qwen-managed-agent, not ${JSON.stringify(name)}.`,
    };
  }
  if (uid !== 0) {
    return {
      error:
        '--service-user changes file owners, so run the bootstrap as root.',
    };
  }
  try {
    const [userId] = lookup('-u', name);
    const [groupId] = lookup('-g', name);
    return { uid: userId, gid: groupId, groups: lookup('-G', name) };
  } catch {
    return {
      error: `User ${name} does not exist; create it first, as systemd/README.md shows.`,
    };
  }
}

// Mirrors the kernel: the owner bits apply to the owner alone, then the group
// bits to any member, then the others bits.
export function accountCanEnter({ uid, gid, mode }, account) {
  if (uid === account.uid) {
    return (mode & 0o100) !== 0;
  }
  if (account.groups.includes(gid)) {
    return (mode & 0o010) !== 0;
  }
  return (mode & 0o001) !== 0;
}

// The directories the kernel enters to reach an absolute directory path: each
// one it looks a name up in, on the way to a symbolic link and along the link's
// target, then the directory the path resolves to.
export async function directoriesToEnter(directory) {
  const entered = [];
  const names = directory.split(path.sep).filter(Boolean);
  let current = path.parse(directory).root;
  let links = 0;
  while (names.length > 0) {
    const name = names.shift();
    entered.push(current);
    if (name === '.') {
      continue;
    }
    if (name === '..') {
      // The current directory is already resolved, so this is its real parent.
      current = path.dirname(current);
      continue;
    }
    const next = path.join(current, name);
    if (!(await lstat(next)).isSymbolicLink()) {
      current = next;
      continue;
    }
    if (++links > MAX_SYMBOLIC_LINKS) {
      throw new Error(`Too many symbolic links in ${directory}.`);
    }
    const target = await readlink(next);
    if (path.isAbsolute(target)) {
      current = path.parse(target).root;
    }
    names.unshift(...target.split(path.sep).filter(Boolean));
  }
  entered.push(current);
  return entered;
}

async function firstBlockedDirectory(directory, account) {
  for (const entered of await directoriesToEnter(directory)) {
    if (!accountCanEnter(await stat(entered), account)) {
      return entered;
    }
  }
  return undefined;
}

async function main() {
  const { values } = parseArgs({
    options: {
      directory: { type: 'string', short: 'd' },
      'key-id': { type: 'string' },
      'service-user': { type: 'string' },
      force: { type: 'boolean', default: false },
    },
  });
  const serviceUser = values['service-user'];
  let account;
  if (serviceUser !== undefined) {
    account = lookupServiceUser(serviceUser, { uid: process.getuid?.() });
    if (account.error) {
      console.error(account.error);
      process.exitCode = 1;
      return;
    }
  }
  const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
  const directory = path.resolve(values.directory ?? path.join(root, 'config'));
  const applicationConfig = path.join(directory, 'application.yml');
  const secrets = generateSecrets(values['key-id'] ?? DEFAULT_KEY_ID);
  // The account owns what it reads; root keeps server.env, which systemd reads,
  // and the SQL, which only an administrator runs.
  const service = account && { uid: account.uid, gid: account.gid };
  const rootGroup = account && { uid: 0, gid: account.gid };
  const files = [
    ['harness.env', renderHarnessEnv(secrets), { owner: service }],
    [
      'server.env',
      renderServerEnv({
        databasePassword: secrets.databasePassword,
        applicationConfigPath: applicationConfig,
        harnessEnvPath: path.join(directory, 'harness.env'),
        serviceUser,
      }),
      account ? { owner: rootGroup, mode: GROUP_FILE_MODE } : {},
    ],
    ['application.yml', renderApplicationYml(secrets), { owner: service }],
    ['mysql-setup.sql', renderMysqlSetup(secrets), {}],
  ];

  if (/['",\r\n]/.test(applicationConfig)) {
    console.error(
      'The configuration directory cannot contain a single quote, comma or newline.',
    );
    process.exitCode = 1;
    return;
  }
  const created = !(await exists(directory));
  await mkdir(directory, { recursive: true, mode: DIRECTORY_MODE });
  if (account) {
    if (created) {
      await chown(directory, 0, account.gid);
      await chmod(directory, GROUP_DIRECTORY_MODE);
    }
    // An existing directory may be shared, such as /etc, so it is left as is.
    const blocked = await firstBlockedDirectory(directory, account);
    if (blocked) {
      console.error(
        `${serviceUser} cannot enter ${blocked}, so the service could not read its files; let it in (chgrp ${serviceUser} and chmod g+x) or choose another directory.`,
      );
      process.exitCode = 1;
      return;
    }
  }
  const lockPath = path.join(directory, '.bootstrap.lock');
  let lock;
  try {
    lock = await open(lockPath, 'wx', 0o600);
  } catch (error) {
    if (error.code === 'EEXIST') {
      console.error(
        'Another bootstrap is running; remove .bootstrap.lock if it is stale.',
      );
      process.exitCode = 1;
      return;
    }
    throw error;
  }
  try {
    if (!values.force) {
      const existing = [];
      for (const [name] of files) {
        if (await exists(path.join(directory, name))) {
          existing.push(name);
        }
      }
      if (existing.length > 0) {
        console.error(
          `Refusing to overwrite ${existing.join(', ')}; pass --force.`,
        );
        process.exitCode = 1;
        return;
      }
    }
    for (const [name, content, options] of files) {
      await writeAtomic(path.join(directory, name), content, options);
    }
  } finally {
    await lock.close();
    await rm(lockPath, { force: true });
  }
  console.log(
    `Wrote ${files.map(([name]) => path.join(directory, name)).join(', ')}`,
  );
  console.log(
    `Run ${path.join(directory, 'mysql-setup.sql')} as a MySQL administrator and delete it,`,
  );
  console.log('create the Workspace directory, then run:');
  console.log('  bin/qwen-managed-agent-server --check');
}

function invokedAsMain() {
  if (!process.argv[1]) {
    return false;
  }
  try {
    return (
      realpathSync(process.argv[1]) ===
      realpathSync(fileURLToPath(import.meta.url))
    );
  } catch {
    return false;
  }
}

if (invokedAsMain()) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
