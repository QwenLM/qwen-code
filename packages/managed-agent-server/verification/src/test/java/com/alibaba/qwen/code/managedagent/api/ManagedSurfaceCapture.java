package com.alibaba.qwen.code.managedagent.api;

import java.util.Map;
import java.util.TreeMap;

/**
 * Prints the committed route twin of {@link SurfaceRegistry} that the
 * TypeScript capability parity matrix reads, and fails the moment the enum
 * and the committed file disagree. Re-capture after an intended registry
 * change with
 *
 * <pre>
 * mvn -Dtest=ManagedSurfaceCaptureTest -Dcapability.parity.capture=true test
 * </pre>
 *
 * which rewrites {@code src/test/resources/capability-parity/managed-surface.txt}.
 */
final class ManagedSurfaceCapture {
    static final String FILE =
            "src/test/resources/capability-parity/managed-surface.txt";

    private ManagedSurfaceCapture() {
    }

    /**
     * One line per route: {@code label method template surface}, sorted by
     * {@code method template}, after the header that records the digest.
     */
    static String render() {
        Map<String, String> lines = new TreeMap<>();
        for (SurfaceRegistry entry : SurfaceRegistry.values()) {
            String surface = entry.surface().name().toLowerCase(
                    java.util.Locale.ROOT);
            lines.put(entry.routeKey(), label(entry) + " " + entry.method()
                    + " " + entry.template() + " " + surface);
        }
        StringBuilder out = new StringBuilder();
        out.append("# Generated by ManagedSurfaceCaptureTest (capture).\n");
        out.append("# sha256 of the route lines below: ")
                .append(digest(routeLines())).append('\n');
        for (String line : lines.values()) {
            out.append(line).append('\n');
        }
        return out.toString();
    }

    static String label(SurfaceRegistry entry) {
        return entry.capabilities().iterator().next().name();
    }

    /** Sorted {@code method template} lines, so the digest is enum-order free. */
    static Iterable<String> routeLines() {
        Map<String, String> lines = new TreeMap<>();
        for (SurfaceRegistry entry : SurfaceRegistry.values()) {
            lines.put(entry.routeKey(), entry.routeKey());
        }
        return lines.values();
    }

    /**
     * The digest the TypeScript side computes: sha256 over the sorted
     * {@code method template} lines, each with a trailing newline.
     */
    static String digest(Iterable<String> routeLines) {
        StringBuilder text = new StringBuilder();
        for (String line : routeLines) {
            text.append(line).append('\n');
        }
        try {
            byte[] hash = java.security.MessageDigest.getInstance("SHA-256")
                    .digest(text.toString().getBytes(java.nio.charset
                            .StandardCharsets.UTF_8));
            return java.util.HexFormat.of().formatHex(hash);
        } catch (java.security.NoSuchAlgorithmException error) {
            throw new IllegalStateException(error);
        }
    }
}
