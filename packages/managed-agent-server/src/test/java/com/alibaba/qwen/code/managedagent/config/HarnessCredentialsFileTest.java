package com.alibaba.qwen.code.managedagent.config;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.boot.env.YamlPropertySourceLoader;
import org.springframework.core.io.ClassPathResource;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class HarnessCredentialsFileTest {
    private static final String TOKEN = "a".repeat(64);
    private static final String DIGEST = "sha256:" + "b".repeat(64);

    @Test
    void theShippedConfigurationBindsTheFileVariable() throws IOException {
        assertThat(new YamlPropertySourceLoader()
                .load("application.yml", new ClassPathResource("application.yml"))
                .get(0).getProperty("qwen.managed-agent.harness.credentials-file"))
                .isEqualTo("${QWEN_MANAGED_AGENT_HARNESS_CREDENTIALS_FILE:}");
    }

    @Test
    void readsBothCredentialsFromTheHarnessEnvironmentFile(@TempDir Path directory) throws IOException {
        Path file = Files.writeString(directory.resolve("harness.env"), String.join("\n",
                "# Generated by qwen-managed-agent-bootstrap.",
                "QWEN_SERVER_TOKEN=replaced-by-the-later-line",
                "",
                "  QWEN_SERVER_TOKEN='" + TOKEN + "'  ",
                "# QWEN_SERVER_TOKEN='commented out, don't",
                "QWEN_HOSTED_HARNESS_CAPABILITY_DIGEST=\"" + DIGEST + "\"",
                "QWEN_HOSTED_HARNESS_BROKER_ARGS=--managed-runtime-broker-token=ignored",
                "not an assignment"));
        ManagedAgentProperties properties = withFile(file);
        properties.validateWorkspaceFiles();
        assertThat(properties.getHarness().getToken()).isEqualTo(TOKEN);
        assertThat(properties.getHarness().getCapabilityDigest()).isEqualTo(DIGEST);
        assertThat(properties.harnessCredentialsApplied()).isTrue();
        // Validation may run again, as preflight's public entry allows.
        properties.validateWorkspaceFiles();
        assertThat(properties.getHarness().getToken()).isEqualTo(TOKEN);
    }

    @Test
    void keepsEveryEqualsSignAfterTheFirst(@TempDir Path directory) throws IOException {
        Path file = Files.writeString(directory.resolve("harness.env"),
                "QWEN_SERVER_TOKEN=QmFzZTY0==\nQWEN_HOSTED_HARNESS_CAPABILITY_DIGEST=" + DIGEST + "\n");
        ManagedAgentProperties properties = withFile(file);
        properties.validateWorkspaceFiles();
        assertThat(properties.getHarness().getToken()).isEqualTo("QmFzZTY0==");
    }

    @Test
    void acceptsEveryCharacterBothReadersTakeLiterally(@TempDir Path directory) throws IOException {
        String token = "AZaz09._:/+=-";
        Path file = Files.writeString(directory.resolve("harness.env"),
                "QWEN_SERVER_TOKEN=" + token + "\nQWEN_HOSTED_HARNESS_CAPABILITY_DIGEST=" + DIGEST + "\n");
        ManagedAgentProperties properties = withFile(file);
        properties.validateWorkspaceFiles();
        assertThat(properties.getHarness().getToken()).isEqualTo(token);
    }

    @Test
    void refusesConstructsTheTwoReadersDisagreeOn(@TempDir Path directory) throws IOException {
        String digest = "QWEN_HOSTED_HARNESS_CAPABILITY_DIGEST=" + DIGEST;
        String secret = "abcdef0123";
        String plain = "a character other than letters, digits and `._:/+=-` in QWEN_SERVER_TOKEN";
        String[][] cases = {
            {"QWEN_SERVER_TOKEN=" + secret + "\\", "a line continuation"},
            {"# a comment that continues\\", "a line continuation"},
            {"QWEN_SERVER_TOKEN=\"" + secret + "\\\"x\"", "an escape inside double quotes"},
            {"QWEN_SERVER_TOKEN='" + secret, "an unterminated quote"},
            {"QWEN_SERVER_TOKEN='" + secret + "' # rotated", "text after a closing quote"},
            {"QWEN_SERVER_TOKEN=" + secret + "\r", "a carriage return"},
            {"; a systemd comment", "a comment starting with `;` instead of `#`"},
            {"  ;QWEN_SERVER_TOKEN=" + secret, "a comment starting with `;` instead of `#`"},
            {"QWEN_SERVER_TOKEN = " + secret, "whitespace around `=` in QWEN_SERVER_TOKEN"},
            {"QWEN_SERVER_TOKEN\t=" + secret, "whitespace around `=` in QWEN_SERVER_TOKEN"},
            {"QWEN_SERVER_TOKEN= " + secret, "whitespace around `=` in QWEN_SERVER_TOKEN"},
            // systemd ignores an `export` line that a shell assigns, and a shell runs the second as a command.
            {"export QWEN_SERVER_TOKEN=" + secret, "a key that is not a bare variable name"},
            {"export HTTPS_PROXY=" + secret, "a key that is not a bare variable name"},
            {"NODE_OPTIONS HTTPS_PROXY=" + secret, "a key that is not a bare variable name"},
            // The Harness row probes only the token, so a digest line must not slip through either.
            {"QWEN_HOSTED_HARNESS_CAPABILITY_DIGEST =sha256:" + secret,
                "whitespace around `=` in QWEN_HOSTED_HARNESS_CAPABILITY_DIGEST"},
            {"QWEN_SERVER_TOKEN=$SHARED_" + secret, plain},
            {"QWEN_SERVER_TOKEN=`cat " + secret + "`", plain},
            {"QWEN_SERVER_TOKEN=" + secret + " " + secret, plain},
            {"QWEN_SERVER_TOKEN=" + secret + ";" + secret, plain},
            {"QWEN_SERVER_TOKEN=" + secret + "&", plain},
            {"QWEN_SERVER_TOKEN=a:~/" + secret, plain},
            {"QWEN_SERVER_TOKEN='" + secret + " " + secret + "'", plain},
        };
        for (String[] refused : cases) {
            Path file = Files.writeString(directory.resolve("harness.env"),
                    "# Generated\n" + digest + "\n" + refused[0] + "\n");
            assertThatThrownBy(withFile(file)::validateWorkspaceFiles).as(refused[0])
                    .isInstanceOf(IllegalStateException.class)
                    .hasMessage("Hosted Harness credentials file " + file + " line 3 uses " + refused[1]
                            + "; write KEY=value without continuations, escapes, expansions or trailing text")
                    .message().doesNotContain(secret);
        }
        // A file saved with CRLF endings stops at its first line, comments included.
        Path crlf = Files.writeString(directory.resolve("crlf.env"),
                "# Generated\r\nQWEN_SERVER_TOKEN=" + TOKEN + "\r\n" + digest + "\r\n");
        assertThatThrownBy(withFile(crlf)::validateWorkspaceFiles)
                .hasMessageStartingWith("Hosted Harness credentials file " + crlf + " line 1 uses a carriage return;");
        // A shell stops at a `;` comment and loses every later line, so it is refused above both
        // keys, between them and after them.
        String[] semicolons = {
            "; rotated\nQWEN_SERVER_TOKEN=" + TOKEN + "\n" + digest + "\n",
            "QWEN_SERVER_TOKEN=" + TOKEN + "\n; rotated\n" + digest + "\n",
            "QWEN_SERVER_TOKEN=" + TOKEN + "\n" + digest + "\n; rotated\n",
        };
        for (int line = 1; line <= semicolons.length; line++) {
            Path semicolon = Files.writeString(directory.resolve("semicolon.env"), semicolons[line - 1]);
            assertThatThrownBy(withFile(semicolon)::validateWorkspaceFiles).as("line %d", line)
                    .hasMessageStartingWith("Hosted Harness credentials file " + semicolon + " line " + line
                            + " uses a comment starting with `;`")
                    .message().doesNotContain(TOKEN);
        }
        // An ignored key may use anything that keeps to a single line.
        Path ignored = Files.writeString(directory.resolve("ignored.env"), "QWEN_SERVER_TOKEN=" + TOKEN + "\n"
                + digest + "\nQWEN_HOSTED_HARNESS_BROKER_ARGS = --a $B --c;~\n");
        ManagedAgentProperties properties = withFile(ignored);
        properties.validateWorkspaceFiles();
        assertThat(properties.getHarness().getToken()).isEqualTo(TOKEN);
    }

    @Test
    void refusesAFileThatCannotBeRead(@TempDir Path directory) {
        Path missing = directory.resolve("missing.env");
        // The type, not a chained cause, reaches preflight's innermost-message row.
        assertThatThrownBy(withFile(missing)::validateWorkspaceFiles)
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("Hosted Harness credentials file " + missing + " cannot be read (NoSuchFileException)")
                .hasNoCause();
    }

    @Test
    void ignoresTheFileWhileTheHarnessIsDisabled(@TempDir Path directory) {
        ManagedAgentProperties properties = withFile(directory.resolve("missing.env"));
        properties.getHarness().setEnabled(false);
        properties.validateWorkspaceFiles();
        assertThat(properties.getHarness().getToken()).isEmpty();
    }

    @Test
    void namesTheMissingOrBlankKey(@TempDir Path directory) throws IOException {
        Path noDigest = Files.writeString(directory.resolve("token-only.env"), "QWEN_SERVER_TOKEN=" + TOKEN + "\n");
        ManagedAgentProperties tokenOnly = withFile(noDigest);
        assertThatThrownBy(tokenOnly::validateWorkspaceFiles)
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("Hosted Harness credentials file " + noDigest
                        + " does not set QWEN_HOSTED_HARNESS_CAPABILITY_DIGEST");
        // A refused file binds neither credential.
        assertThat(tokenOnly.getHarness().getToken()).isEmpty();
        assertThat(tokenOnly.harnessCredentialsApplied()).isFalse();
        Path blankToken = Files.writeString(directory.resolve("blank.env"),
                "QWEN_SERVER_TOKEN=''\nQWEN_HOSTED_HARNESS_CAPABILITY_DIGEST=" + DIGEST + "\n");
        assertThatThrownBy(withFile(blankToken)::validateWorkspaceFiles)
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("Hosted Harness credentials file " + blankToken + " does not set QWEN_SERVER_TOKEN");
    }

    @Test
    void refusesASecondSourceForEitherCredential(@TempDir Path directory) throws IOException {
        Path file = Files.writeString(directory.resolve("harness.env"),
                "QWEN_SERVER_TOKEN=" + TOKEN + "\nQWEN_HOSTED_HARNESS_CAPABILITY_DIGEST=" + DIGEST + "\n");
        ManagedAgentProperties token = withFile(file);
        token.getHarness().setToken(TOKEN);
        ManagedAgentProperties digest = withFile(file);
        digest.getHarness().setCapabilityDigest(DIGEST);
        for (ManagedAgentProperties properties : new ManagedAgentProperties[] {token, digest}) {
            assertThatThrownBy(properties::validateWorkspaceFiles)
                    .isInstanceOf(IllegalStateException.class)
                    .hasMessage("Configure the Hosted Harness token and capability digest either in"
                            + " harness.credentials-file or directly, not both");
        }
    }

    @Test
    void sharesTheBrokerTokenWhenTheFileCarriesIt(@TempDir Path directory) throws IOException {
        String credentials = "QWEN_SERVER_TOKEN=" + TOKEN + "\nQWEN_HOSTED_HARNESS_CAPABILITY_DIGEST=" + DIGEST + "\n";
        Path shared = Files.writeString(directory.resolve("shared.env"), credentials
                + "QWEN_MANAGED_RUNTIME_BROKER_URL=http://127.0.0.1:4182\n"
                + "QWEN_MANAGED_RUNTIME_BROKER_TOKEN=broker-token\n");
        ManagedAgentProperties fromFile = withFile(shared);
        fromFile.validateWorkspaceFiles();
        assertThat(fromFile.getRuntimeBroker().getToken()).isEqualTo("broker-token");
        // Preflight compares the URL with the address the Broker binds.
        assertThat(fromFile.harnessBrokerUrl()).isEqualTo("http://127.0.0.1:4182");
        // Both readers take the brackets of an IPv6 literal as they are.
        Path ipv6 = Files.writeString(directory.resolve("ipv6.env"), credentials
                + "QWEN_MANAGED_RUNTIME_BROKER_URL=http://[::1]:4182\n"
                + "QWEN_MANAGED_RUNTIME_BROKER_TOKEN=broker-token\n");
        ManagedAgentProperties bracketed = withFile(ipv6);
        bracketed.validateWorkspaceFiles();
        assertThat(bracketed.harnessBrokerUrl()).isEqualTo("http://[::1]:4182");

        // The Harness takes the URL and token together, so one without the other binds nothing.
        String[] halves = {"QWEN_MANAGED_RUNTIME_BROKER_TOKEN=broker-token",
            "QWEN_MANAGED_RUNTIME_BROKER_URL=http://127.0.0.1:4182"};
        for (String half : halves) {
            Path file = Files.writeString(directory.resolve("half.env"), credentials + half + "\n");
            ManagedAgentProperties properties = withFile(file);
            assertThatThrownBy(properties::validateWorkspaceFiles).as(half)
                    .isInstanceOf(IllegalStateException.class)
                    .hasMessage("Set QWEN_MANAGED_RUNTIME_BROKER_URL and QWEN_MANAGED_RUNTIME_BROKER_TOKEN"
                            + " together in harness.credentials-file, or neither");
            assertThat(properties.getRuntimeBroker().getToken()).isEmpty();
            assertThat(properties.getHarness().getToken()).isEmpty();
            assertThat(properties.harnessCredentialsApplied()).isFalse();
        }
        // The Harness takes an empty value as set, and then refuses to start
        // without the other half, so the file cannot pass as setting neither.
        for (String empty : new String[] {
                "QWEN_MANAGED_RUNTIME_BROKER_URL=", "QWEN_MANAGED_RUNTIME_BROKER_TOKEN=''"}) {
            String key = empty.substring(0, empty.indexOf('='));
            Path file = Files.writeString(directory.resolve("empty.env"), credentials + empty + "\n");
            ManagedAgentProperties properties = withFile(file);
            assertThatThrownBy(properties::validateWorkspaceFiles).as(empty)
                    .isInstanceOf(IllegalStateException.class)
                    .hasMessage("Hosted Harness credentials file " + file + " sets " + key
                            + " to an empty value, which the Hosted Harness refuses; set it or remove the line");
            assertThat(properties.harnessBrokerUrl()).isEmpty();
            assertThat(properties.harnessCredentialsApplied()).isFalse();
        }

        ManagedAgentProperties twice = withFile(shared);
        twice.getRuntimeBroker().setToken("direct-token");
        assertThatThrownBy(twice::validateWorkspaceFiles)
                .isInstanceOf(IllegalStateException.class)
                .hasMessage("Configure the Runtime Broker token either in"
                        + " harness.credentials-file or directly, not both");
        assertThat(twice.getHarness().getToken()).isEmpty();
        assertThat(twice.harnessBrokerUrl()).isEmpty();
        assertThat(twice.harnessCredentialsApplied()).isFalse();

        // Without the key, for example on a text-only deployment, the direct value stays in charge.
        Path textOnly = Files.writeString(directory.resolve("text-only.env"), credentials);
        ManagedAgentProperties direct = withFile(textOnly);
        direct.getRuntimeBroker().setToken("direct-token");
        direct.validateWorkspaceFiles();
        assertThat(direct.getRuntimeBroker().getToken()).isEqualTo("direct-token");

        // The Harness reads these lines too, so they are held to the same rules as the other two.
        for (String[] refused : new String[][] {
            {"QWEN_MANAGED_RUNTIME_BROKER_TOKEN =broker-token",
                "whitespace around `=` in QWEN_MANAGED_RUNTIME_BROKER_TOKEN"},
            {"QWEN_MANAGED_RUNTIME_BROKER_TOKEN=broker&token",
                "a character other than letters, digits and `._:/+=-` in QWEN_MANAGED_RUNTIME_BROKER_TOKEN"},
            {"QWEN_MANAGED_RUNTIME_BROKER_TOKEN=broker[token]",
                "a character other than letters, digits and `._:/+=-` in QWEN_MANAGED_RUNTIME_BROKER_TOKEN"},
            {"export QWEN_MANAGED_RUNTIME_BROKER_TOKEN=broker-token", "a key that is not a bare variable name"},
            {"QWEN_MANAGED_RUNTIME_BROKER_URL =http://127.0.0.1:4182",
                "whitespace around `=` in QWEN_MANAGED_RUNTIME_BROKER_URL"},
            {"QWEN_MANAGED_RUNTIME_BROKER_URL=http://h;rm",
                "a character other than letters, digits, `[`, `]` and `._:/+=-` in QWEN_MANAGED_RUNTIME_BROKER_URL"},
        }) {
            Path file = Files.writeString(directory.resolve("refused.env"), credentials + refused[0] + "\n");
            assertThatThrownBy(withFile(file)::validateWorkspaceFiles).as(refused[0])
                    .hasMessageStartingWith(
                            "Hosted Harness credentials file " + file + " line 3 uses " + refused[1] + ";");
        }
    }

    @Test
    void leavesDirectCredentialsAloneWithoutAFile() {
        ManagedAgentProperties properties = new ManagedAgentProperties();
        properties.getHarness().setToken(TOKEN);
        properties.getHarness().setCapabilityDigest(DIGEST);
        properties.validateWorkspaceFiles();
        assertThat(properties.getHarness().getToken()).isEqualTo(TOKEN);
        assertThat(properties.getHarness().getCapabilityDigest()).isEqualTo(DIGEST);
    }

    private static ManagedAgentProperties withFile(Path file) {
        ManagedAgentProperties properties = new ManagedAgentProperties();
        properties.getHarness().setEnabled(true);
        properties.getSessionStore().setEnabled(true);
        properties.getHarness().setCredentialsFile(file.toString());
        return properties;
    }
}
